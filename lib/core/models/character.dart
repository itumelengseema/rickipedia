class Character {
  final int id;
  final String name;
  final String status;
  final String gender;
  final String origin;
  final String imageUrl;
  final int episodesAppearedOn;

  const Character({
    required this.id,
    required this.name,
    required this.status,
    required this.gender,
    required this.origin,
    required this.episodesAppearedOn,
    required this.imageUrl,
  });

  
}
